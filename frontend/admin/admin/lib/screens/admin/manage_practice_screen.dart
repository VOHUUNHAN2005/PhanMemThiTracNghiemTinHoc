import 'package:admin/services/admin_api_service.dart';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import '../widgets/admin_ui_kit.dart';
import 'exam_questions_screen.dart';

class ManagePracticeScreen extends StatefulWidget {
  const ManagePracticeScreen({super.key});

  @override
  State createState() => _ManagePracticeScreenState();
}

class _ManagePracticeScreenState extends State {
  final _api = AdminApiService();

  List _exams = [];
  List _topics = [];
  int? _filterTopicId;
  bool _isLoading = true;

  @override
  void initState() {
    super.initState();
    _loadData();
  }

  Future _loadData() async {
    setState(() => _isLoading = true);
    try {
      final results = await Future.wait([
        _api.getExams(loaiBoDe: 'LUYEN_TAP', maChuDe: _filterTopicId),
        _api.getTopics(),
      ]);
      if (!mounted) return;
      setState(() {
        _exams = List.from(results[0]);
        _topics = List.from(results[1]);
      });
    } catch (e) {
      _showSnack(e.toString(), isError: true);
    } finally {
      if (mounted) setState(() => _isLoading = false);
    }
  }

  void _showSnack(String msg, {bool isError = false}) {
    if (!mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text(msg),
        backgroundColor:
            isError ? const Color(0xFFDC2626) : const Color(0xFF16A34A),
      ),
    );
  }

  Widget _buildStatusBadge(String? status) {
    Color bg = const Color(0xFFF1F5F9);
    Color fg = const Color(0xFF475569);
    String label = 'Bản nháp';

    if (status == 'CONG_KHAI') {
      bg = const Color(0xFFDCFCE7);
      fg = const Color(0xFF15803D);
      label = 'Công khai';
    } else if (status == 'AN') {
      bg = const Color(0xFFFEE2E2);
      fg = const Color(0xFFDC2626);
      label = 'Đang ẩn';
    }

    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
      decoration:
          BoxDecoration(color: bg, borderRadius: BorderRadius.circular(20)),
      child: Text(label,
          style:
              TextStyle(fontSize: 12, fontWeight: FontWeight.bold, color: fg)),
    );
  }

  Future _openAutoGenerateDialog() async {
    if (_topics.isEmpty) {
      _showSnack('Vui lòng tạo Chủ đề và thêm câu hỏi vào Ngân hàng trước.',
          isError: true);
      return;
    }

    int selectedTopicId = _filterTopicId ?? _topics.first['MaChuDe'];
    final prefixCtrl = TextEditingController();
    final numExamsCtrl = TextEditingController(text: '5');
    final easyCtrl = TextEditingController(text: '10');
    final medCtrl = TextEditingController(text: '6');
    final hardCtrl = TextEditingController(text: '4');
    final passScoreCtrl = TextEditingController(text: '5.0');
    String selectedStatus = 'CONG_KHAI';

    Map getSelectedTopic() {
      return _topics.firstWhere(
        (t) => t['MaChuDe'] == selectedTopicId,
        orElse: () =>
            {'SoCauDe': 0, 'SoCauTrungBinh': 0, 'SoCauKho': 0, 'TenChuDe': ''},
      );
    }

    final saved = await showModernModal(
      context: context,
      title: 'Sinh Bộ đề Ôn tập Tự động',
      subtitle:
          'Chia đều câu hỏi từ kho thành các đề không trùng lặp để thí sinh ôn trọn bộ kiến thức',
      icon: Icons.auto_awesome_rounded,
      accentColor: const Color(0xFF4F46E5),
      width: 600,
      confirmText: 'Bắt đầu sinh đề ôn',
      bodyBuilder: (ctx, setModalState) {
        final topic = getSelectedTopic();
        final availEasy = (topic['SoCauDe'] ?? 0) as int;
        final availMed = (topic['SoCauTrungBinh'] ?? 0) as int;
        final availHard = (topic['SoCauKho'] ?? 0) as int;

        final numExams = int.tryParse(numExamsCtrl.text.trim()) ?? 0;
        final perEasy = int.tryParse(easyCtrl.text.trim()) ?? 0;
        final perMed = int.tryParse(medCtrl.text.trim()) ?? 0;
        final perHard = int.tryParse(hardCtrl.text.trim()) ?? 0;

        final reqEasy = numExams * perEasy;
        final reqMed = numExams * perMed;
        final reqHard = numExams * perHard;
        final totalPerExam = perEasy + perMed + perHard;

        final okEasy = availEasy >= reqEasy;
        final okMed = availMed >= reqMed;
        final okHard = availHard >= reqHard;
        final validNumExams = numExams >= 1 && numExams <= 50;
        final allEnough =
            okEasy && okMed && okHard && validNumExams && totalPerExam > 0;

        return Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            modernDropdownField(
              value: selectedTopicId,
              label: 'Chọn Chủ đề nguồn *',
              prefixIcon: Icons.layers_outlined,
              items: _topics.map((t) {
                return buildModernDropdownItem(
                  value: t['MaChuDe'],
                  text:
                      '${t['TenChuDe']} (Kho: ${t['SoCauDe'] ?? 0} Dễ · ${t['SoCauTrungBinh'] ?? 0} TB · ${t['SoCauKho'] ?? 0} Khó)',
                  icon: Icons.layers_rounded,
                  iconColor: const Color(0xFF4F46E5),
                );
              }).toList(),
              onChanged: (val) =>
                  setModalState(() => selectedTopicId = val as int),
            ),
            const SizedBox(height: 12),
            Container(
              padding: const EdgeInsets.all(14),
              decoration: BoxDecoration(
                color: allEnough
                    ? const Color(0xFFF0FDF4)
                    : const Color(0xFFFEF2F2),
                borderRadius: BorderRadius.circular(12),
                border: Border.all(
                  color: allEnough
                      ? const Color(0xFF86EFAC)
                      : const Color(0xFFFECACA),
                ),
              ),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Row(
                    children: [
                      Icon(
                        allEnough
                            ? Icons.check_circle_rounded
                            : Icons.warning_amber_rounded,
                        size: 18,
                        color: allEnough
                            ? const Color(0xFF16A34A)
                            : const Color(0xFFDC2626),
                      ),
                      const SizedBox(width: 8),
                      Expanded(
                        child: Text(
                          !validNumExams
                              ? 'Số lượng đề mỗi lần sinh phải từ 1 đến 50 đề.'
                              : totalPerExam <= 0
                                  ? 'Mỗi đề phải có ít nhất 1 câu hỏi.'
                                  : allEnough
                                      ? 'Kho đủ câu hỏi! Sẽ sinh $numExams đề × $totalPerExam câu/đề = ${numExams * totalPerExam} câu.'
                                      : 'Kho câu hỏi chưa đủ định mức để chia đều $numExams đề ôn:',
                          style: TextStyle(
                            fontWeight: FontWeight.bold,
                            fontSize: 13,
                            color: allEnough
                                ? const Color(0xFF15803D)
                                : const Color(0xFF991B1B),
                          ),
                        ),
                      ),
                    ],
                  ),
                  const SizedBox(height: 8),
                  Text(
                    '• Dễ: Cần $reqEasy / Kho có $availEasy ${okEasy ? "✅" : "(Thiếu ${reqEasy - availEasy})"}   '
                    '• TB: Cần $reqMed / Kho có $availMed ${okMed ? "✅" : "(Thiếu ${reqMed - availMed})"}   '
                    '• Khó: Cần $reqHard / Kho có $availHard ${okHard ? "✅" : "(Thiếu ${reqHard - availHard})"}',
                    style: const TextStyle(
                        fontSize: 12.5, color: Color(0xFF334155)),
                  ),
                ],
              ),
            ),
            const SizedBox(height: 16),
            Row(
              children: [
                Expanded(
                  flex: 2,
                  child: TextField(
                    controller: prefixCtrl,
                    maxLength: 100,
                    decoration: modernInputDecoration(
                      label: 'Tiền tố tên bộ đề (Tùy chọn)',
                      hint: 'VD: Ôn tập ${topic['TenChuDe']}',
                      prefixIcon: Icons.title_rounded,
                    ).copyWith(counterText: ''),
                  ),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: TextField(
                    controller: numExamsCtrl,
                    keyboardType: TextInputType.number,
                    inputFormatters: [
                      FilteringTextInputFormatter.digitsOnly,
                      LengthLimitingTextInputFormatter(2),
                    ],
                    onChanged: (_) => setModalState(() {}),
                    decoration: modernInputDecoration(
                      label: 'Số lượng đề (1-50) *',
                      hint: '5',
                      prefixIcon: Icons.copy_all_rounded,
                    ),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 16),
            const Text(
              'Cơ cấu độ khó cho MỖI đề ôn tập:',
              style: TextStyle(
                  fontWeight: FontWeight.bold,
                  fontSize: 13.5,
                  color: Color(0xFF0F172A)),
            ),
            const SizedBox(height: 10),
            Row(
              children: [
                Expanded(
                  child: TextField(
                    controller: easyCtrl,
                    keyboardType: TextInputType.number,
                    inputFormatters: [
                      FilteringTextInputFormatter.digitsOnly,
                      LengthLimitingTextInputFormatter(3),
                    ],
                    onChanged: (_) => setModalState(() {}),
                    decoration: modernInputDecoration(
                      label: 'Số câu Dễ / đề',
                      prefixIcon: Icons.signal_cellular_alt_1_bar_rounded,
                    ),
                  ),
                ),
                const SizedBox(width: 10),
                Expanded(
                  child: TextField(
                    controller: medCtrl,
                    keyboardType: TextInputType.number,
                    inputFormatters: [
                      FilteringTextInputFormatter.digitsOnly,
                      LengthLimitingTextInputFormatter(3),
                    ],
                    onChanged: (_) => setModalState(() {}),
                    decoration: modernInputDecoration(
                      label: 'Số câu TB / đề',
                      prefixIcon: Icons.signal_cellular_alt_2_bar_rounded,
                    ),
                  ),
                ),
                const SizedBox(width: 10),
                Expanded(
                  child: TextField(
                    controller: hardCtrl,
                    keyboardType: TextInputType.number,
                    inputFormatters: [
                      FilteringTextInputFormatter.digitsOnly,
                      LengthLimitingTextInputFormatter(3),
                    ],
                    onChanged: (_) => setModalState(() {}),
                    decoration: modernInputDecoration(
                      label: 'Số câu Khó / đề',
                      prefixIcon: Icons.signal_cellular_alt_rounded,
                    ),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 16),
            Row(
              children: [
                Expanded(
                  child: TextField(
                    controller: passScoreCtrl,
                    keyboardType:
                        const TextInputType.numberWithOptions(decimal: true),
                    inputFormatters: [
                      FilteringTextInputFormatter.allow(
                          RegExp(r'^\d{0,2}(\.\d{0,2})?$')),
                    ],
                    decoration: modernInputDecoration(
                      label: 'Điểm đạt (0 - 10) *',
                      hint: '5.0',
                      prefixIcon: Icons.grade_outlined,
                    ),
                  ),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: modernDropdownField(
                    value: selectedStatus,
                    label: 'Trạng thái sau khi sinh',
                    prefixIcon: Icons.visibility_outlined,
                    items: [
                      buildModernDropdownItem(
                        value: 'CONG_KHAI',
                        text: 'Công khai ngay',
                        icon: Icons.public_rounded,
                        iconColor: const Color(0xFF16A34A),
                      ),
                      buildModernDropdownItem(
                        value: 'NHAP',
                        text: 'Lưu bản nháp',
                        icon: Icons.edit_note_rounded,
                        iconColor: const Color(0xFF64748B),
                      ),
                    ],
                    onChanged: (val) =>
                        setModalState(() => selectedStatus = val as String),
                  ),
                ),
              ],
            ),
          ],
        );
      },
      onConfirm: () async {
        final numExams = int.tryParse(numExamsCtrl.text.trim());
        final perEasy = int.tryParse(easyCtrl.text.trim()) ?? 0;
        final perMed = int.tryParse(medCtrl.text.trim()) ?? 0;
        final perHard = int.tryParse(hardCtrl.text.trim()) ?? 0;
        final passScore = double.tryParse(passScoreCtrl.text.trim());

        if (numExams == null || numExams < 1 || numExams > 50) {
          _showSnack('Số lượng đề phải là số nguyên từ 1 đến 50.',
              isError: true);
          return false;
        }
        if (perEasy + perMed + perHard < 1) {
          _showSnack('Tổng số câu mỗi đề phải có ít nhất 1 câu.',
              isError: true);
          return false;
        }
        if (passScore == null || passScore < 0 || passScore > 10) {
          _showSnack('Điểm đạt phải là số hợp lệ từ 0 đến 10.', isError: true);
          return false;
        }

        final topic = getSelectedTopic();
        if ((topic['SoCauDe'] ?? 0) < numExams * perEasy ||
            (topic['SoCauTrungBinh'] ?? 0) < numExams * perMed ||
            (topic['SoCauKho'] ?? 0) < numExams * perHard) {
          _showSnack(
              'Kho câu hỏi của chủ đề này không đủ định mức để sinh $numExams đề ôn.',
              isError: true);
          return false;
        }

        try {
          final res = await _api.autoGenerateExams({
            'MaChuDe': selectedTopicId,
            'LoaiBoDe': 'LUYEN_TAP',
            'TienToTieuDe': prefixCtrl.text.trim(),
            'SoLuongDe': numExams,
            'SoCauDe': perEasy,
            'SoCauTrungBinh': perMed,
            'SoCauKho': perHard,
            'ThoiGianLamBai': null,
            'DiemDatToiThieu': passScore,
            'TrangThai': selectedStatus,
          });
          _showSnack(res['message'] ?? 'Đã sinh bộ đề ôn tập thành công.');
          return true;
        } catch (e) {
          _showSnack(e.toString(), isError: true);
          return false;
        }
      },
    );

    if (saved == true) _loadData();
  }

  Future _openExamFormDialog({Map? exam}) async {
    if (_topics.isEmpty) {
      _showSnack('Vui lòng tạo ít nhất 1 Chủ đề trước khi tạo Bộ đề ôn tập.',
          isError: true);
      return;
    }

    final isEdit = exam != null;
    final titleCtrl =
        TextEditingController(text: isEdit ? (exam['TieuDe'] ?? '') : '');
    final descCtrl =
        TextEditingController(text: isEdit ? (exam['MoTa'] ?? '') : '');
    final passScoreCtrl = TextEditingController(
      text: isEdit ? (exam['DiemDatToiThieu'] ?? 5.0).toString() : '5.0',
    );

    int selectedTopicId = isEdit
        ? (exam['MaChuDe'] ?? _topics.first['MaChuDe'])
        : (_filterTopicId ?? _topics.first['MaChuDe']);
    String selectedStatus =
        isEdit ? (exam['TrangThai'] ?? 'CONG_KHAI') : 'CONG_KHAI';

    final saved = await showModernModal(
      context: context,
      title: isEdit ? 'Cập nhật Bộ đề Ôn tập' : 'Tạo Bộ đề Ôn tập thủ công',
      subtitle:
          'Bộ đề luyện tập không giới hạn thời gian giúp thí sinh ôn kiến thức theo chủ đề',
      icon: Icons.menu_book_rounded,
      accentColor: const Color(0xFF2563EB),
      width: 540,
      confirmText: isEdit ? 'Lưu thay đổi' : 'Tạo bộ đề',
      bodyBuilder: (ctx, setModalState) => Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          TextField(
            controller: titleCtrl,
            maxLength: 150,
            decoration: modernInputDecoration(
              label: 'Tiêu đề bộ đề * (Tối thiểu 3 ký tự)',
              hint: 'VD: Ôn tập Chương 1 - Kiến trúc máy tính',
              prefixIcon: Icons.title_rounded,
            ).copyWith(counterText: ''),
          ),
          const SizedBox(height: 16),
          modernDropdownField(
            value: selectedTopicId,
            label: 'Thuộc chủ đề *',
            prefixIcon: Icons.layers_outlined,
            items: _topics.map((t) {
              return buildModernDropdownItem(
                value: t['MaChuDe'],
                text: t['TenChuDe'] ?? '',
                icon: Icons.layers_rounded,
                iconColor: const Color(0xFF2563EB),
              );
            }).toList(),
            onChanged: (val) =>
                setModalState(() => selectedTopicId = val as int),
          ),
          const SizedBox(height: 16),
          Row(
            children: [
              Expanded(
                child: TextField(
                  controller: passScoreCtrl,
                  keyboardType:
                      const TextInputType.numberWithOptions(decimal: true),
                  inputFormatters: [
                    FilteringTextInputFormatter.allow(
                        RegExp(r'^\d{0,2}(\.\d{0,2})?$')),
                  ],
                  decoration: modernInputDecoration(
                    label: 'Điểm đạt (0 - 10) *',
                    hint: '5.0',
                    prefixIcon: Icons.grade_outlined,
                  ),
                ),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: modernDropdownField(
                  value: selectedStatus,
                  label: 'Trạng thái hiển thị',
                  prefixIcon: Icons.visibility_outlined,
                  items: [
                    buildModernDropdownItem(
                      value: 'NHAP',
                      text: 'Bản nháp',
                      icon: Icons.edit_note_rounded,
                      iconColor: const Color(0xFF64748B),
                    ),
                    buildModernDropdownItem(
                      value: 'CONG_KHAI',
                      text: 'Công khai',
                      icon: Icons.public_rounded,
                      iconColor: const Color(0xFF16A34A),
                    ),
                    buildModernDropdownItem(
                      value: 'AN',
                      text: 'Ẩn',
                      icon: Icons.visibility_off_outlined,
                      iconColor: const Color(0xFFDC2626),
                    ),
                  ],
                  onChanged: (val) =>
                      setModalState(() => selectedStatus = val as String),
                ),
              ),
            ],
          ),
          const SizedBox(height: 16),
          TextField(
            controller: descCtrl,
            maxLines: 3,
            maxLength: 500,
            decoration: modernInputDecoration(
              label: 'Mô tả bộ đề',
              hint: 'Nhập hướng dẫn hoặc ghi chú cho bộ đề ôn tập...',
              prefixIcon: Icons.notes_rounded,
            ).copyWith(counterText: ''),
          ),
        ],
      ),
      onConfirm: () async {
        final title = titleCtrl.text.trim();
        if (title.length < 3) {
          _showSnack('Tiêu đề bộ đề phải có ít nhất 3 ký tự.', isError: true);
          return false;
        }

        final passScore = double.tryParse(passScoreCtrl.text.trim());
        if (passScore == null || passScore < 0 || passScore > 10) {
          _showSnack('Điểm đạt phải là số hợp lệ từ 0 đến 10.', isError: true);
          return false;
        }

        final payload = {
          'TieuDe': title,
          'MoTa': descCtrl.text.trim(),
          'LoaiBoDe': 'LUYEN_TAP',
          'MaChuDe': selectedTopicId,
          'ThoiGianLamBai': null,
          'DiemDatToiThieu': passScore,
          'TrangThai': selectedStatus,
        };

        try {
          if (isEdit) {
            await _api.updateExam(exam['MaBoDe'], payload);
            _showSnack('Đã cập nhật bộ đề ôn tập.');
          } else {
            await _api.createExam(payload);
            _showSnack('Đã tạo bộ đề ôn tập mới.');
          }
          return true;
        } catch (e) {
          _showSnack(e.toString(), isError: true);
          return false;
        }
      },
    );

    if (saved == true) _loadData();
  }

  Future _confirmDeleteExam(Map exam) async {
    final confirm = await showModernConfirmDialog(
      context: context,
      title: 'Xóa bộ đề ôn tập?',
      message: 'Toàn bộ liên kết câu hỏi trong bộ đề này sẽ bị gỡ bỏ.',
      highlightText: exam['TieuDe'] ?? '',
      confirmText: 'Xóa bộ đề',
    );

    if (confirm != true) return;

    try {
      await _api.deleteExam(exam['MaBoDe']);
      _showSnack('Đã xóa bộ đề.');
      _loadData();
    } catch (e) {
      _showSnack(e.toString(), isError: true);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: const EdgeInsets.all(24),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Row(
            children: [
              SizedBox(
                width: 260,
                child: modernFilterDropdown(
                  value: _filterTopicId,
                  hint: 'Tất cả chủ đề',
                  icon: Icons.filter_list_rounded,
                  items: [
                    buildModernDropdownItem(
                      value: null,
                      text: 'Tất cả chủ đề',
                      icon: Icons.apps_rounded,
                      iconColor: const Color(0xFF475569),
                    ),
                    ..._topics.map((t) => buildModernDropdownItem(
                          value: t['MaChuDe'],
                          text: t['TenChuDe'] ?? '',
                          icon: Icons.layers_rounded,
                          iconColor: const Color(0xFF2563EB),
                        )),
                  ],
                  onChanged: (val) {
                    setState(() => _filterTopicId = val as int?);
                    _loadData();
                  },
                ),
              ),
              const SizedBox(width: 16),
              Text(
                'Tổng: ${_exams.length} bộ đề',
                style: const TextStyle(
                    color: Color(0xFF64748B), fontWeight: FontWeight.w500),
              ),
              const Spacer(),
              IconButton(
                tooltip: 'Tải lại',
                onPressed: _loadData,
                icon: const Icon(Icons.refresh),
              ),
              const SizedBox(width: 8),
              ElevatedButton.icon(
                style: ElevatedButton.styleFrom(
                  backgroundColor: const Color(0xFF4F46E5),
                  foregroundColor: Colors.white,
                  padding:
                      const EdgeInsets.symmetric(horizontal: 16, vertical: 14),
                ),
                onPressed: _openAutoGenerateDialog,
                icon: const Icon(Icons.auto_awesome_rounded, size: 18),
                label: const Text('Sinh đề tự động'),
              ),
              const SizedBox(width: 10),
              ElevatedButton.icon(
                style: ElevatedButton.styleFrom(
                  backgroundColor: const Color(0xFF2563EB),
                  foregroundColor: Colors.white,
                  padding:
                      const EdgeInsets.symmetric(horizontal: 16, vertical: 14),
                ),
                onPressed: () => _openExamFormDialog(),
                icon: const Icon(Icons.add),
                label: const Text('Tạo thủ công'),
              ),
            ],
          ),
          const SizedBox(height: 16),
          Expanded(
            child: Container(
              decoration: BoxDecoration(
                color: Colors.white,
                borderRadius: BorderRadius.circular(12),
                border: Border.all(color: const Color(0xFFE2E8F0)),
              ),
              child: _isLoading
                  ? const Center(child: CircularProgressIndicator())
                  : _exams.isEmpty
                      ? const Center(child: Text('Chưa có bộ đề ôn tập nào.'))
                      : AdminScrollableTable(
                          child: DataTable(
                            columnSpacing: 22,
                            headingRowColor: WidgetStateProperty.all(
                                const Color(0xFFF8FAFC)),
                            columns: const [
                              DataColumn(label: Text('Mã')),
                              DataColumn(label: Text('Tiêu đề Bộ đề')),
                              DataColumn(label: Text('Chủ đề')),
                              DataColumn(label: Text('Cơ cấu câu hỏi')),
                              DataColumn(label: Text('Điểm đạt')),
                              DataColumn(label: Text('Trạng thái')),
                              DataColumn(label: Text('Thao tác')),
                            ],
                            rows: _exams.map((e) {
                              final de = e['SoCauDe'] ?? 0;
                              final tb = e['SoCauTrungBinh'] ?? 0;
